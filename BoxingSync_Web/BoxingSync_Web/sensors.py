"""Read the logger's event export and pair clock-synchronized device triggers."""
import csv
from pathlib import Path

import numpy as np
from scipy.optimize import linear_sum_assignment


def read_events(path, glove_role='1', helmet_role='2', extra_helmet=None):
    def load(source):
        with Path(source).open(newline='', encoding='utf-8-sig') as stream:
            rows = list(csv.DictReader(stream))
        if not rows or not {'t_s', 'kind', 'role', 'peak_V'}.issubset(rows[0]):
            raise ValueError("Expected event CSV fields t_s, kind, role, peak_V.")
        return rows

    rows = load(path)
    if extra_helmet:
        rows.extend(load(extra_helmet))
    points = []
    seen = set()
    for row in rows:
        if row['kind'].strip().upper() != 'EVENT':
            continue
        role = row['role'].strip()
        if role not in (glove_role, helmet_role):
            continue
        time = float(row['t_s'])
        peak = float(row['peak_V'])
        if not np.isfinite(time) or not np.isfinite(peak):
            raise ValueError("Sensor times and peak voltages must be finite.")
        identity = role,time,peak
        if identity in seen:
            continue
        seen.add(identity)
        points.append({'sensor_s': time, 'peak_v': peak, 'seq': row.get('seq', ''),
                       'device': 'glove' if role == glove_role else 'helmet',
                       'synced': (row.get('synced') or '1').strip() in ('1', 'true', 'True')})
    if not points:
        raise ValueError("No device EVENT rows for configured roles.")
    return sorted(points, key=lambda p:p['sensor_s'])


def associate(reference, observed, gate):
    """Globally match unique events inside a tolerance, allowing unmatched rows."""
    if len(reference) == 0 or len(observed) == 0:
        return []
    distances = np.abs(np.asarray(reference)[:, None]-np.asarray(observed)[None, :])
    cost = np.column_stack((distances, np.full((len(reference),len(reference)), gate)))
    ii, jj = linear_sum_assignment(cost)
    return [(int(i),int(j)) for i,j in zip(ii,jj)
            if j < len(observed) and distances[i,j] < gate]


def device_pairs(points, tolerance=.052):
    glove = [p for p in points if p['device'] == 'glove']
    head = [p for p in points if p['device'] == 'helmet']
    gi = [i for i,p in enumerate(glove) if p['synced']]
    hi = [i for i,p in enumerate(head) if p['synced']]
    matched = associate([glove[i]['sensor_s'] for i in gi],
                        [head[j]['sensor_s'] for j in hi], tolerance)
    return glove, head, {gi[i]:hi[j] for i,j in matched}


def align(glove, head, paired, visual, search, manual=None):
    from itertools import combinations
    if not np.isfinite(search) or search < .05 or search > 120:
        raise ValueError("Use a finite --max-offset from 0.05 to 120 s.")
    if manual:
        x = np.array([float(p['sensor_s']) for p in manual])
        y = np.array([float(p['video_s']) for p in manual])
        if not np.all(np.isfinite(x)) or not np.all(np.isfinite(y)):
            raise ValueError("Manual anchor times must be finite.")
        if len(x)>1 and np.ptp(x)>=3:
            a,b = np.polyfit(x,y,1)
        else:
            a,b = 1., np.median(y-x)
        if not .97 <= a <= 1.03 or np.max(abs(y-(a*x+b))) > .18:
            raise ValueError("Manual anchors disagree. Use the same visible events on both clocks.")
        return make_alignment(a,b,x,y,'manual_anchors',None)

    x = np.array([head[j]['sensor_s'] for j in paired.values()])
    if len(x)<3 or len(visual)<3:
        raise ValueError("Need 3 or more paired sensor hits and visible approaches for auto-sync. Enter matching times in Advanced setup → Manual sync anchors.")
    vt = np.array([v['video_s'] for v in visual])
    strength = np.array([np.clip((v['reach_px']+98)/80,.18,1) for v in visual])
    glove_only = np.array([p['sensor_s'] for i,p in enumerate(glove)
                           if i not in paired and p['synced'] and p['peak_v']>=1.5])
    # Test candidate offsets generated by actual event coincidences. The
    # tighter weighting rewards several precise agreements over near misses.
    offsets = (vt[None,:]-x[:,None]).flatten()
    offsets = np.unique(np.round(offsets[abs(offsets)<=search],3))
    if not len(offsets):
        raise ValueError("No time alignments inside --max-offset. Enter matching times in Advanced setup → Manual sync anchors.")
    proposals = []
    for b in offsets:
        distance = abs(x[:,None]+b-vt[None,:])
        scores = np.exp(-.5*(distance/.092)**2)*strength[None,:]
        proposals.append((float(scores.max(axis=1).sum()), float(b)))
    proposals.sort(reverse=True)
    top = []
    for score,b in proposals:
        if all(abs(b-old)>.32 for _,old in top):
            top.append((score,b))
        if len(top) == 12:
            break

    fits = []
    for _,seed in top:
        initial = associate(x+seed, vt, .22)
        if len(initial) < 3:
            continue
        possible = [(1.,seed)]
        for (i,j),(k,l) in combinations(initial,2):
            if abs(x[k]-x[i])<5:
                continue
            a=(vt[l]-vt[j])/(x[k]-x[i])
            if .985 <= a <= 1.015:
                possible.append((a,vt[j]-a*x[i]))
        for a,b in possible:
            d = abs(a*x[:,None]+b-vt[None,:])
            quality = np.exp(-.5*(d/.083)**2)*strength[None,:]
            matches = associate(a*x+b,vt,.18)
            score = sum(quality[i,j] for i,j in matches)
            if len(matches)>=3:
                # Glove-only contacts break ties between bouts of similarly
                # spaced head hits. These do not set the fitted clock.
                available = np.array([j for j in range(len(vt))
                                      if j not in {index for _,index in matches}],dtype=int)
                auxiliary = associate(a*glove_only+b,vt[available],.28)
                score += .22*len(auxiliary)
                fits.append((score,a,b,matches))
    if not fits:
        raise ValueError("Auto-sync could not establish a consistent match. Enter matching times in Advanced setup → Manual sync anchors.")
    score,a,b,pairs = max(fits,key=lambda f:f[0])
    rival = max((f[0] for f in fits if abs((f[1]-a)*np.median(x)+f[2]-b)>.30), default=0)
    if len(pairs)<4 or (rival and rival>score*.82):
        raise ValueError("Auto-sync has too few or ambiguous anchors. Enter matching times in Advanced setup → Manual sync anchors.")
    xx = np.array([x[i] for i,j in pairs])
    yy = np.array([vt[j] for i,j in pairs])
    if np.ptp(xx) >= 10 and len(xx)>=5:
        a,b=np.polyfit(xx,yy,1)
    else:
        a,b=1.,np.median(yy-xx)
    return make_alignment(a,b,xx,yy,'visual_approaches',float(rival/score))


def make_alignment(a,b,x,y,method,rival_ratio):
    residual = y-(a*x+b)
    return {'method':method,'scale':float(a),'offset_s':float(b),'drift_ppm':float((a-1)*1e6),
            'rmse_s':float(np.sqrt(np.mean(residual**2))),
            'max_abs_residual_s':float(np.max(abs(residual))),
            'alternative_score_ratio':rival_ratio,
            'anchors':[{'sensor_s':float(i),'video_s':float(j),'residual_s':float(r)}
                       for i,j,r in zip(x,y,residual)]}
